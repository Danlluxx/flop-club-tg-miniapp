export const tournamentLegalNote =
  "Турнир проходит в формате спортивно-развлекательного мероприятия. Турнирные фишки не имеют денежной стоимости и не подлежат обмену. Денежный призовой фонд не формируется.";

export function tournamentRuleFor(title: string) {
  return rules[title] ?? {
    title: title.toUpperCase(),
    short: "Турнир FLOP CLUB в спортивно-развлекательном формате.",
    rule: "Турнир FLOP CLUB в спортивно-развлекательном формате.",
    features: defaultFeatures
  };
}

export function tournamentPriceFeatures(tournament: Tournament) {
  const features = [`Вход ${new Intl.NumberFormat("ru-RU").format(tournament.buyIn)} ₽`];

  if (tournament.profile !== "FREEZE" && tournament.reEntry > 0) {
    features.push(`Re-entry ${new Intl.NumberFormat("ru-RU").format(tournament.reEntry)} ₽ до конца поздней регистрации`);
  } else if (!rules[tournament.title]?.features.includes("Без re-entry")) {
    features.push("Без re-entry");
  }

  return features;
}
